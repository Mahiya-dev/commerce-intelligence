import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { Connection, RowDataPacket } from "mysql2/promise";

/**
 * Minimal, auditable migration runner for MySQL/MariaDB on cPanel.
 *
 * - Files: db/migrations/NNNN_name.sql, applied in filename order.
 * - Ledger: schema_migrations(version, checksum, applied_at).
 * - Applied files are immutable: a changed checksum aborts the run.
 * - MySQL DDL auto-commits, so files must be re-runnable (IF NOT EXISTS);
 *   on failure nothing is recorded and the fixed file can be re-applied.
 * - A named lock prevents two concurrent runs.
 */
export type MigrationFile = { version: string; sql: string; checksum: string };

const FILE_RE = /^(\d{4})_[a-z0-9_]+\.sql$/;

export function checksum(sql: string): string {
  return createHash("sha256").update(sql.replace(/\r\n/g, "\n")).digest("hex");
}

export function loadMigrations(dir: string): MigrationFile[] {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const seen = new Set<string>();
  return files.map((file) => {
    const m = FILE_RE.exec(file);
    if (!m) throw new Error(`Nama file migrasi tidak valid: ${file} (format: 0001_nama.sql)`);
    if (seen.has(m[1])) throw new Error(`Nomor migrasi duplikat: ${m[1]}`);
    seen.add(m[1]);
    const sql = readFileSync(join(dir, file), "utf8");
    return { version: file.replace(/\.sql$/, ""), sql, checksum: checksum(sql) };
  });
}

const LEDGER_DDL = `CREATE TABLE IF NOT EXISTS schema_migrations (
  version     VARCHAR(255) NOT NULL,
  checksum    CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  applied_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci`;

export type MigrationPlan = { applied: string[]; pending: MigrationFile[]; unknown: string[] };

export async function planMigrations(conn: Connection, files: MigrationFile[]): Promise<MigrationPlan> {
  await conn.query(LEDGER_DDL);
  const [rows] = await conn.query<RowDataPacket[]>("SELECT version, checksum FROM schema_migrations ORDER BY version");
  const ledger = new Map(rows.map((r) => [r.version as string, r.checksum as string]));
  for (const f of files) {
    const recorded = ledger.get(f.version);
    if (recorded && recorded !== f.checksum) {
      throw new Error(
        `Migrasi ${f.version} sudah diterapkan tetapi isinya berubah (checksum berbeda). ` +
          `Jangan mengubah migrasi lama; buat migrasi baru.`,
      );
    }
  }
  const known = new Set(files.map((f) => f.version));
  return {
    applied: files.filter((f) => ledger.has(f.version)).map((f) => f.version),
    pending: files.filter((f) => !ledger.has(f.version)),
    unknown: [...ledger.keys()].filter((v) => !known.has(v)),
  };
}

/** `conn` MUST be created with multipleStatements: true. */
export async function runMigrations(
  conn: Connection,
  files: MigrationFile[],
  log: (msg: string) => void = () => {},
): Promise<string[]> {
  const [[lock]] = await conn.query<RowDataPacket[]>("SELECT GET_LOCK('uci_schema_migrate', 30) AS acquired");
  if (Number(lock.acquired) !== 1) throw new Error("Migrasi lain sedang berjalan (lock tidak didapat).");
  try {
    const plan = await planMigrations(conn, files);
    for (const v of plan.unknown) log(`⚠ Tercatat di database tetapi file tidak ada: ${v}`);
    const applied: string[] = [];
    for (const f of plan.pending) {
      log(`→ Menerapkan ${f.version}`);
      await conn.query(f.sql);
      await conn.query("INSERT INTO schema_migrations (version, checksum) VALUES (?, ?)", [f.version, f.checksum]);
      applied.push(f.version);
    }
    return applied;
  } finally {
    await conn.query("SELECT RELEASE_LOCK('uci_schema_migrate')");
  }
}

/**
 * Single SQL file for phpMyAdmin → Import, for hosts where the CLI cannot
 * reach the database. Includes the ledger rows so the CLI stays consistent.
 */
export function buildImportBundle(files: MigrationFile[]): string {
  const escape = (s: string) => s.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
  const parts = [
    "-- Uray Commerce Intelligence — migration bundle for phpMyAdmin (Import tab).",
    "-- Generated by `npm run db:bundle`. Import into the EMPTY or partially migrated database.",
    "-- Every statement is re-runnable; already-applied files are skipped by the ledger insert.",
    "",
    `${LEDGER_DDL};`,
    "",
  ];
  for (const f of files) {
    parts.push(`-- ===== ${f.version} =====`, f.sql.trim(), "");
    parts.push(
      `INSERT IGNORE INTO schema_migrations (version, checksum) VALUES ('${escape(f.version)}', '${f.checksum}');`,
      "",
    );
  }
  return parts.join("\n");
}
